        private static readonly IReadOnlyDictionary<string, HashSet<string>> KnownNamesBySection =
            KnownPaths
                .SelectMany(path =>
                {
                    string[] parts = path.Split('/');
                    return parts.Skip(1)
                        .Where(part => part != "[]")
                        .Select(part => (Section: parts[0], Name: part));
                })
                .GroupBy(entry => entry.Section, StringComparer.OrdinalIgnoreCase)
                .ToDictionary(
                    group => group.Key,
                    group => group.Select(entry => entry.Name).ToHashSet(StringComparer.OrdinalIgnoreCase),
                    StringComparer.OrdinalIgnoreCase);

        internal static bool Contains(string path) => KnownPaths.Contains(Normalize(path));

        internal static bool ContainsOrHasKnownAncestor(string path)
        {
            string normalized = Normalize(path);
            while (!string.IsNullOrEmpty(normalized))
            {
                if (KnownPaths.Contains(normalized))
                    return true;

                int separator = normalized.LastIndexOf('/');
                normalized = separator < 0 ? string.Empty : normalized[..separator];
            }

            return false;
        }

        internal static bool IsKnownName(string section, string name) =>
            KnownNamesBySection.TryGetValue(section, out HashSet<string> names) && names.Contains(name);

        internal static string Normalize(string path) => string.Join(
            "/",
            path.Replace('\\', '/').Split('/').Select(segment =>
                int.TryParse(segment, out _) ? "[]" : segment));
    }
